/*
# Offer System — Tables, RLS, and Core Functions

## Overview
Adds a complete offer/survey/app-install earning system integrated into the existing
GoldClicks PTC platform. This migration creates the database schema, RLS policies,
and SECURITY DEFINER RPC functions for offer tracking, conversion crediting,
reversals, and admin management.

## New Tables

### offer_providers
Stores configuration for third-party offer/survey/app providers.
- id (uuid PK)
- slug (text, unique) — e.g. 'adgem', 'offertoro', 'cpx_research'
- display_name (text)
- provider_type (text) — 'survey' | 'app_install' | 'offerwall' | 'game'
- enabled (boolean, default false)
- api_key_encrypted (text) — server-side only, never exposed to client
- postback_secret_encrypted (text) — server-side only
- publisher_id (text) — publisher/affiliate ID for tracking URL generation
- postback_url (text) — the URL providers should call (informational; the actual
  edge function URL is fixed per project)
- currency_code (text, default 'USD')
- reward_margin_percent (numeric, default 100) — percent of provider reward passed to user
- config (jsonb) — provider-specific configuration (tracking domains, sub IDs, etc.)
- created_at, updated_at (timestamptz)

### offers
Catalog of available offers from providers. Populated by provider API or admin.
- id (uuid PK)
- provider_id (uuid FK → offer_providers, CASCADE)
- provider_offer_id (text) — the offer's ID at the provider
- title, description, requirements (text)
- offer_type (text) — 'survey' | 'app_install' | 'game' | 'signup' | 'trial' | 'other'
- reward (numeric(18,8)) — reward amount in platform currency
- currency_code (text, default 'USD')
- icon_url (text)
- destination_url (text) — provider tracking URL template
- platform (text) — 'android' | 'ios' | 'web' | 'all'
- estimated_time_minutes (integer)
- difficulty (text) — 'easy' | 'medium' | 'hard'
- category (text)
- active (boolean, default true)
- start_date, end_date (timestamptz, nullable)
- created_at, updated_at (timestamptz)
- UNIQUE(provider_id, provider_offer_id)

### offer_sessions
Tracks every offer click/start by a user. One row per click.
- id (uuid PK)
- user_id (uuid FK → auth.users, CASCADE)
- offer_id (uuid FK → offers, SET NULL — keep session even if offer deleted)
- provider_id (uuid FK → offer_providers, CASCADE)
- provider_slug (text) — denormalized for quick lookups in webhooks
- provider_offer_id (text) — denormalized
- offer_type (text) — denormalized
- tracking_id (text, unique) — generated by the platform, sent to provider as sub_id/click_id
- click_id (text) — provider's click ID if returned
- status (text) — 'clicked' | 'started' | 'pending' | 'completed' | 'rejected' | 'reversed' | 'expired'
- reward (numeric(18,8)) — snapshot of reward at click time
- currency_code (text)
- provider_conversion_id (text) — set on conversion, unique for idempotency
- revenue (numeric(18,8)) — provider-side revenue if supplied
- metadata (jsonb) — extra provider data
- expires_at (timestamptz) — session expiry
- created_at, completed_at, reversed_at (timestamptz)
- Indexes on (user_id, created_at), (tracking_id), (provider_conversion_id), (provider_slug, status)

### offer_conversions
Immutable audit trail of every conversion/reversal event from providers.
- id (uuid PK)
- session_id (uuid FK → offer_sessions, CASCADE)
- user_id (uuid FK → auth.users, CASCADE)
- provider_id (uuid FK → offer_providers, CASCADE)
- provider_conversion_id (text) — provider's transaction ID
- event_type (text) — 'conversion' | 'reversal'
- reward (numeric(18,8))
- revenue (numeric(18,8))
- status (text) — 'processed' | 'duplicate' | 'rejected'
- raw_payload (jsonb) — full provider postback data for audit
- created_at (timestamptz)
- UNIQUE(provider_id, provider_conversion_id, event_type)

## RPC Functions (all SECURITY DEFINER)

### offer_start_session(p_offer_id uuid)
Called when user clicks Start on an offer. Creates an offer_session with status='clicked',
generates a unique tracking_id, and returns it along with the provider tracking URL.
Only works for active, enabled-provider offers. User must have status='active'.

### offer_list_available(p_offer_type text, p_platform text)
Returns available offers (active, enabled provider, within date range) with provider info.
Filters by offer_type ('all' for no filter) and platform ('all' for no filter).

### offer_list_my_sessions(p_status text, p_limit int, p_offset int)
Returns the authenticated user's offer sessions with offer title/provider info.
Filters by status ('all' for no filter).

### offer_get_session(p_session_id uuid)
Returns details for a single offer session owned by the caller.

### offer_process_conversion(
  p_provider_slug text, p_tracking_id text, p_conversion_id text,
  p_reward numeric, p_revenue numeric, p_event_type text, p_raw jsonb
)
Called ONLY by the offer-webhook edge function (service role). This is the
authoritative credit/reversal path:
1. Validates the provider exists and is enabled.
2. Finds the session by tracking_id.
3. Checks for duplicate conversion_id (idempotency).
4. For 'conversion': marks session completed, credits available_balance + total_earned,
   inserts ledger transaction with unique reference 'offer:<session_id>'.
5. For 'reversal': marks session reversed, debits the balance, inserts reversal ledger entry.
6. Records every event in offer_conversions (even duplicates, marked 'duplicate').

### offer_admin_stats()
Returns aggregate offer statistics for admin dashboard.

### offer_admin_list_sessions(
  p_provider_slug text, p_offer_type text, p_status text,
  p_user_id uuid, p_limit int, p_offset int
)
Returns all offer sessions with user info for admin management. Admin-only.

### offer_admin_list_providers()
Returns all provider configurations for admin. Does NOT expose encrypted secrets.
Admin-only.

### offer_admin_update_provider(
  p_provider_id uuid, p_enabled boolean, p_display_name text,
  p_publisher_id text, p_reward_margin_percent numeric, p_config jsonb
)
Updates non-secret provider configuration. Admin-only.

### offer_admin_set_provider_secret(
  p_provider_id uuid, p_secret_type text, p_secret_value text
)
Sets encrypted API key or postback secret. Admin-only. Secret is encrypted with
pgp_sym_encrypt using a server-side key.

## Security

- RLS enabled on all tables.
- Users can only SELECT their own offer_sessions and offer_conversions.
- Users can SELECT active offers and enabled providers (no secrets exposed).
- Users CANNOT INSERT/UPDATE/DELETE offers, providers, or conversions.
- offer_start_session is the only user-writable path (via RPC), and it only creates sessions.
- offer_process_conversion has NO grants to anon/authenticated — only the service role
  (edge function) can call it. This is enforced by REVOKE EXECUTE FROM PUBLIC and
  not granting to anon/authenticated.
- All admin functions check is_admin() internally.
- Provider secrets are encrypted at rest and never returned to any client.
- The transactions ledger is reused — offer rewards use type='offer_reward' with
  reference='offer:<session_id>' for idempotency.

## Important Notes
1. The existing transactions table gains two new type values: 'offer_reward' and 'offer_reversal'.
   The CHECK constraint on transactions.type is dropped and recreated to include these.
2. The existing profiles table is NOT modified — offer rewards update the same
   available_balance and total_earned columns using the same SECURITY DEFINER pattern.
3. No second balance system is created.
4. All money movement uses FOR UPDATE locking on profiles, same as ptc_claim.
5. Provider secrets use pgp_sym_encrypt — requires pgcrypto extension (already enabled
   in the existing database if not, it's added here with CREATE EXTENSION IF NOT EXISTS).
*/

