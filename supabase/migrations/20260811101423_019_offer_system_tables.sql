-- =============================================================
-- FUNCTION: offer_start_session (user-facing)
-- =============================================================
CREATE OR REPLACE FUNCTION offer_start_session(p_offer_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user uuid := auth.uid();
  v_profile profiles%ROWTYPE;
  v_offer offers%ROWTYPE;
  v_provider offer_providers%ROWTYPE;
  v_session offer_sessions%ROWTYPE;
  v_tracking_id text;
  v_tracking_url text;
BEGIN
  IF v_user IS NULL THEN
    RETURN jsonb_build_object('error', 'Not authenticated');
  END IF;

  SELECT * INTO v_profile FROM profiles WHERE id = v_user FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('error', 'Profile not found');
  END IF;
  IF v_profile.status != 'active' THEN
    RETURN jsonb_build_object('error', 'Account is not active');
  END IF;

  SELECT * INTO v_offer FROM offers WHERE id = p_offer_id AND active = true FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('error', 'Offer not available');
  END IF;

  SELECT * INTO v_provider FROM offer_providers WHERE id = v_offer.provider_id AND enabled = true FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('error', 'Provider not available');
  END IF;

  -- Check date validity
  IF v_offer.start_date IS NOT NULL AND now() < v_offer.start_date THEN
    RETURN jsonb_build_object('error', 'Offer not yet available');
  END IF;
  IF v_offer.end_date IS NOT NULL AND now() > v_offer.end_date THEN
    RETURN jsonb_build_object('error', 'Offer has expired');
  END IF;

  -- Generate tracking ID
  v_tracking_id := encode(gen_random_bytes(16), 'hex');

  -- Insert session
  INSERT INTO offer_sessions (
    user_id, offer_id, provider_id, provider_slug, provider_offer_id,
    offer_type, tracking_id, status, reward, currency_code, expires_at
  ) VALUES (
    v_user, v_offer.id, v_provider.id, v_provider.slug, v_offer.provider_offer_id,
    v_offer.offer_type, v_tracking_id, 'clicked', v_offer.reward, v_offer.currency_code,
    now() + interval '24 hours'
  ) RETURNING * INTO v_session;

  -- Build tracking URL — replace placeholders in destination_url
  v_tracking_url := v_offer.destination_url;
  v_tracking_url := replace(v_tracking_url, '[SUB_ID]', v_tracking_id);
  v_tracking_url := replace(v_tracking_url, '[USER_ID]', v_user::text);
  v_tracking_url := replace(v_tracking_url, '[PUBLISHER_ID]', v_provider.publisher_id);
  v_tracking_url := replace(v_tracking_url, '[OFFER_ID]', v_offer.provider_offer_id);

  RETURN jsonb_build_object(
    'session_id', v_session.id,
    'tracking_id', v_tracking_id,
    'tracking_url', v_tracking_url,
    'reward', v_offer.reward,
    'currency', v_offer.currency_code,
    'offer_type', v_offer.offer_type,
    'title', v_offer.title
  );
END;
$$;

REVOKE EXECUTE ON FUNCTION offer_start_session(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION offer_start_session(uuid) TO authenticated;

-- =============================================================
-- FUNCTION: offer_list_available (user-facing)
-- =============================================================
CREATE OR REPLACE FUNCTION offer_list_available(
  p_offer_type text DEFAULT 'all',
  p_platform text DEFAULT 'all'
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user uuid := auth.uid();
BEGIN
  IF v_user IS NULL THEN
    RETURN '[]'::jsonb;
  END IF;

  RETURN COALESCE((
    SELECT jsonb_agg(jsonb_build_object(
      'id', o.id,
      'provider_id', o.provider_id,
      'provider_slug', p.slug,
      'provider_name', p.display_name,
      'provider_offer_id', o.provider_offer_id,
      'title', o.title,
      'description', o.description,
      'requirements', o.requirements,
      'offer_type', o.offer_type,
      'reward', o.reward,
      'currency_code', o.currency_code,
      'icon_url', o.icon_url,
      'destination_url', o.destination_url,
      'platform', o.platform,
      'estimated_time_minutes', o.estimated_time_minutes,
      'difficulty', o.difficulty,
      'category', o.category
    ) ORDER BY o.reward DESC)
    FROM offers o
    JOIN offer_providers p ON p.id = o.provider_id
    WHERE o.active = true
      AND p.enabled = true
      AND (o.start_date IS NULL OR now() >= o.start_date)
      AND (o.end_date IS NULL OR now() <= o.end_date)
      AND (p_offer_type = 'all' OR o.offer_type = p_offer_type)
      AND (p_platform = 'all' OR o.platform = 'all' OR o.platform = p_platform)
  ), '[]'::jsonb);
END;
$$;

REVOKE EXECUTE ON FUNCTION offer_list_available(text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION offer_list_available(text, text) TO authenticated;

