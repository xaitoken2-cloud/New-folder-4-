-- =============================================================
-- FUNCTION: offer_admin_list_sessions (admin-only)
-- =============================================================
CREATE OR REPLACE FUNCTION offer_admin_list_sessions(
  p_provider_slug text DEFAULT NULL,
  p_offer_type text DEFAULT NULL,
  p_status text DEFAULT NULL,
  p_user_id uuid DEFAULT NULL,
  p_limit int DEFAULT 100,
  p_offset int DEFAULT 0
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_is_admin boolean;
BEGIN
  SELECT is_admin() INTO v_is_admin;
  IF NOT v_is_admin THEN
    RETURN '[]'::jsonb;
  END IF;

  RETURN COALESCE((
    SELECT jsonb_agg(jsonb_build_object(
      'id', s.id,
      'user_id', s.user_id,
      'username', p.username,
      'email', p.email,
      'provider_slug', s.provider_slug,
      'provider_offer_id', s.provider_offer_id,
      'offer_type', s.offer_type,
      'status', s.status,
      'reward', s.reward,
      'revenue', s.revenue,
      'provider_conversion_id', s.provider_conversion_id,
      'tracking_id', s.tracking_id,
      'created_at', s.created_at,
      'completed_at', s.completed_at,
      'reversed_at', s.reversed_at,
      'offer_title', o.title
    ) ORDER BY s.created_at DESC)
    FROM offer_sessions s
    LEFT JOIN profiles p ON p.id = s.user_id
    LEFT JOIN offers o ON o.id = s.offer_id
    WHERE (p_provider_slug IS NULL OR s.provider_slug = p_provider_slug)
      AND (p_offer_type IS NULL OR s.offer_type = p_offer_type)
      AND (p_status IS NULL OR s.status = p_status)
      AND (p_user_id IS NULL OR s.user_id = p_user_id)
    LIMIT p_limit OFFSET p_offset
  ), '[]'::jsonb);
END;
$$;

