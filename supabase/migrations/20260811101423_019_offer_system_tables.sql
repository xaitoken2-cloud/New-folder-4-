    'reversed_at', v_session.reversed_at,
    'metadata', v_session.metadata,
    'offer_title', v_offer.title,
    'offer_description', v_offer.description,
    'offer_requirements', v_offer.requirements,
    'offer_icon', v_offer.icon_url,
    'offer_platform', v_offer.platform,
    'estimated_time_minutes', v_offer.estimated_time_minutes,
